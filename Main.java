public class Main {
    public static void main(String[] args) {
        // Массив балансов 5 расчетных счетов (есть положительные и отрицательные)
        int[] balances = {15000, -2300, 4500, -700, 0};

        System.out.println("Список должников (отрицательный баланс):");
        
        // Цикл проверяет каждый счет
        for (int i = 0; i < balances.length; i++) {
            // Ветвление if отбирает только те счета, баланс которых ушел в минус
            if (balances[i] < 0) {
                // Выводим номер счета (индекс + 1) и сумму
                System.out.println("Счет №" + (i + 1) + " | Баланс: " + balances[i] + " руб.");
            }
        }

        System.out.println("Модуль успешно инициализирован в Git!");
    }
}
